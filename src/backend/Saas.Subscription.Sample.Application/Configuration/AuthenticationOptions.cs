using System.ComponentModel.DataAnnotations;

namespace Saas.Subscription.Sample.Application.Configuration;

/// <summary>
/// Access-token settings: who issues the token, for which API, for how long and signed with which key.
/// </summary>
public sealed class AuthenticationOptions
{
    public const string SectionName = "Authentication";

    [Required]
    public string? Issuer { get; set; }

    [Required]
    public string? Audience { get; set; }

    /// <summary>10-minute baseline (plan §5A).</summary>
    [Range(typeof(TimeSpan), "00:01:00", "01:00:00")]
    public TimeSpan AccessTokenLifetime { get; set; } = TimeSpan.FromMinutes(10);

    /// <summary>
    /// Secret. The ES256 private key as an unencrypted PEM (NIST P-256); line breaks may be written as <c>\n</c>.
    /// Required in every environment and never generated by the application, so tokens survive a restart and
    /// every instance signs with the same key. Never logged.
    /// </summary>
    public string? SigningKey { get; set; }

    /// <summary>The <c>kid</c> header of issued tokens; a token naming another key is rejected. Not a secret.</summary>
    public string? SigningKeyId { get; set; }
}
